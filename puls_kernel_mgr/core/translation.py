class TranslationManager:
    _instance = None
    
    def __new__(cls):
        if cls._instance is None:
            cls._instance = super(TranslationManager, cls).__new__(cls)
            cls._instance.current_lang = "en"
            cls._instance.load_preference()
        return cls._instance

    def load_preference(self):
        try:
            if _PREFS_FILE.exists():
                prefs = json.loads(_PREFS_FILE.read_text())
                self.current_lang = prefs.get("lang", "en")
                if self.current_lang not in _TRANSLATIONS:
                    self.current_lang = "en"
        except Exception:
            self.current_lang = "en"

    def save_preference(self, lang):
        if lang in _TRANSLATIONS:
            self.current_lang = lang
            try:
                _PREFS_FILE.parent.mkdir(parents=True, exist_ok=True)
                prefs = {}
                if _PREFS_FILE.exists():
                    try:
                        prefs = json.loads(_PREFS_FILE.read_text())
                    except Exception:
                        pass
                prefs["lang"] = lang
                _PREFS_FILE.write_text(json.dumps(prefs))
            except Exception:
                pass

    def tr(self, key, **kwargs):
        lang = self.current_lang
        lang_dict = _TRANSLATIONS.get(lang, _TRANSLATIONS["en"])
        val = lang_dict.get(key)
        if val is None:
            val = _TRANSLATIONS["en"].get(key, key)
        return val.format(**kwargs) if kwargs else val

    def get_current_lang(self):
        return self.current_lang

    def toggle_lang(self):
        new_lang = "tr" if self.current_lang == "en" else "en"
        self.save_preference(new_lang)
        return new_lang

    def get(self, key, **kwargs):
        return self.tr(key, **kwargs)

    def set_lang(self, lang):
        self.save_preference(lang)
